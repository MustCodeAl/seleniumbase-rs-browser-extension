// Generates ready-to-run Rust code for seleniumbase-rs ContextOptions,
// evasion::Fingerprint, and the `antibot-detector` plugin crate.

import type { PageProbe } from "./fingerprint.ts";
import { rustStr } from "./rust.ts";

export interface RustContextOptionsCode {
  filename: string;
  code: string;
}

/**
 * Generates idiomatic, ready-to-run Rust code constructing
 * `seleniumbase_rs::sb_cdp::ContextOptions` with `seleniumbase_rs::evasion::Fingerprint`.
 */
export function generateRustContextOptions(probe: PageProbe, options: { fnName?: string } = {}): RustContextOptionsCode {
  const nav = probe.navigator ?? {};
  const scr = probe.screen ?? {};
  const tz = probe.timezone?.name;
  const gl = probe.webgl;
  const fnName = options.fnName ?? "create_browser_context_options";

  const lines: string[] = [];
  lines.push("//! Generated by seleniumbase-rs companion");
  if (probe.url) {
    lines.push(`//! Profile captured from: ${probe.url}`);
  }
  lines.push(`//! Date: ${new Date().toISOString()}`);
  lines.push("");
  lines.push("use seleniumbase_rs::evasion::Fingerprint;");
  lines.push("use seleniumbase_rs::sb_cdp::ContextOptions;");
  lines.push("use seleniumbase_rs::Result;");
  lines.push("");
  lines.push("/// Build `ContextOptions` replicating this browser profile and viewport.");
  lines.push(`pub fn ${fnName}() -> Result<ContextOptions> {`);
  lines.push("    let fingerprint = Fingerprint::builder()");

  if (nav.userAgent) {
    lines.push(`        .user_agent(${rustStr(nav.userAgent)})`);
  }
  if (nav.language) {
    lines.push(`        .locale(${rustStr(nav.language)})`);
  }
  if (nav.platform) {
    lines.push(`        .platform(${rustStr(nav.platform)})`);
  }
  if (tz) {
    lines.push(`        .timezone(${rustStr(tz)})`);
  }
  if (typeof scr.width === "number" && typeof scr.height === "number") {
    lines.push(`        .screen(${Math.round(scr.width)}, ${Math.round(scr.height)})`);
  }
  if (typeof nav.hardwareConcurrency === "number" && nav.hardwareConcurrency > 0) {
    lines.push(`        .hardware_concurrency(${nav.hardwareConcurrency})`);
  }
  if (typeof nav.deviceMemory === "number" && Number.isFinite(nav.deviceMemory) && nav.deviceMemory > 0) {
    const memory = Number.isInteger(nav.deviceMemory) ? `${nav.deviceMemory}.0` : `${nav.deviceMemory}`;
    lines.push(`        .device_memory(${memory})`);
  }

  // WebGL vendor/renderer spoof if available
  const unmaskedRenderer = gl?.unmaskedRenderer ?? gl?.renderer;
  const unmaskedVendor = gl?.unmaskedVendor ?? gl?.vendor;
  if (unmaskedRenderer || unmaskedVendor) {
    lines.push("        // Replicated WebGL graphics hardware profile");
    lines.push("        // Vendor: " + (unmaskedVendor ?? "Default"));
    lines.push("        // Renderer: " + (unmaskedRenderer ?? "Default"));
  }

  lines.push("        .build()?;");
  lines.push("");
  lines.push("    let options = ContextOptions::builder()");
  lines.push("        .fingerprint(&fingerprint)");
  lines.push("        .build()?;");
  lines.push("");
  lines.push("    Ok(options)");
  lines.push("}");
  lines.push("");
  lines.push("/// Example usage in pure CDP or testing:");
  lines.push("/// ```no_run");
  lines.push("/// use seleniumbase_rs::sb_cdp::Browser;");
  lines.push("///");
  lines.push("/// # async fn run(browser: Browser) -> seleniumbase_rs::Result<()> {");
  lines.push(`/// let options = ${fnName}()?;`);
  lines.push("/// let context = browser.new_context_with(options).await?;");
  lines.push(`/// let page = context.new_page_at(${rustStr(probe.url ?? "https://example.com")}).await?;`);
  lines.push("/// # Ok(())");
  lines.push("/// # }");
  lines.push("/// ```");

  const filename = "context_options.rs";
  return {
    filename,
    code: lines.join("\n") + "\n",
  };
}

/**
 * Generates ready-to-run Rust code using the `antibot-detector` plugin crate
 * to detect Cloudflare, DataDome, Akamai, Kasada, PerimeterX, etc.
 */
export function generateRustAntibotDetectorCode(url = "https://example.com"): string {
  return `//! Automated anti-bot detection script using the \`antibot-detector\` plugin crate.
use antibot_detector::{AntibotDetector, Cookie, Page as DetectorPage};
use seleniumbase_rs::sb_cdp::{Browser, LaunchOptions};
use seleniumbase_rs::tokio;

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let browser = Browser::launch(LaunchOptions::default()).await?;
    let page = browser.new_page_at(${rustStr(url)}).await?;
    let html = page.content().await?;
    let cookies: Vec<Cookie> = page
        .cookies()
        .all()
        .await?
        .into_iter()
        .map(|c| Cookie::new(c.name, c.value))
        .collect();
    let detector_page = DetectorPage::new(html)
        .with_url(${rustStr(url)})
        .with_cookies(cookies);

    // Instantiate antibot-detector plugin
    let detector = AntibotDetector::new();
    let detections = detector.detect(&detector_page)?;

    if detections.is_empty() {
        println!("No anti-bot challenges or WAF protections detected.");
    } else {
        for d in detections {
            println!(
                "Detected: {} ({}) - Confidence: {}% - Blocked: {}",
                d.provider(),
                d.category(),
                d.confidence(),
                d.is_blocked()
            );
        }
    }

    browser.close().await?;
    Ok(())
}
`;
}
